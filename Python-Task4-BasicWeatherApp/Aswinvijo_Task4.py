import requests

# Enter your OpenWeatherMap API key
API_KEY = input("Enter your OpenWeatherMap API key: ").strip()

# Ask for city or ZIP code
location = input("Enter city name or ZIP code: ").strip()

# Check if input is empty
if not location:
    print("Error: City name or ZIP code cannot be empty.")

else:
    url = "https://api.openweathermap.org/data/2.5/weather"

    # If the input contains only numbers, treat it as an Indian ZIP code
    if location.isdigit():
        params = {
            "zip": location + ",IN",
            "appid": API_KEY,
            "units": "metric"
        }
    else:
        params = {
            "q": location,
            "appid": API_KEY,
            "units": "metric"
        }

    try:
        # Send request to OpenWeatherMap
        response = requests.get(url, params=params, timeout=10)

        # Invalid API key
        if response.status_code == 401:
            print("Error: Invalid API key.")

        # City/ZIP not found
        elif response.status_code == 404:
            print("Error: City or ZIP code not found.")

        # Too many requests
        elif response.status_code == 429:
            print("Error: Too many requests. Try again later.")

        else:
            response.raise_for_status()

            # Convert API response to JSON
            data = response.json()

            # Extract required information
            city = data["name"]
            country = data["sys"]["country"]

            temperature_c = data["main"]["temp"]
            temperature_f = (temperature_c * 9 / 5) + 32

            humidity = data["main"]["humidity"]
            condition = data["weather"][0]["description"].title()
            wind_speed = data["wind"]["speed"]

            # Display weather information
            print("\n======================================")
            print("          WEATHER INFORMATION")
            print("======================================")

            print(f"Location       : {city}, {country}")
            print(f"Temperature    : {temperature_c:.2f} °C")
            print(f"Temperature    : {temperature_f:.2f} °F")
            print(f"Humidity       : {humidity}%")
            print(f"Condition      : {condition}")
            print(f"Wind Speed     : {wind_speed} m/s")

            print("======================================")

    except requests.exceptions.Timeout:
        print("Error: Request timed out.")

    except requests.exceptions.ConnectionError:
        print("Error: Could not connect to the internet.")

    except requests.exceptions.RequestException:
        print("Error: Unable to get weather information.")

    except (KeyError, ValueError):
        print("Error: Could not read the weather data.")