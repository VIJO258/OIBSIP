import random
import string

def generate_password():
    print("\n===== RANDOM PASSWORD GENERATOR =====")

    # Get password length
    try:
        length = int(input("Enter password length (minimum 8): "))

        if length < 8:
            print("Error: Password length must be at least 8.")
            return

    except ValueError:
        print("Error: Please enter a valid number.")
        return

    # Select character types
    print("\nChoose character types:")
    print("1. Uppercase letters (A-Z)")
    print("2. Lowercase letters (a-z)")
    print("3. Numbers (0-9)")
    print("4. Symbols (!, @, #, etc.)")

    choices = input(
        "Enter your choices separated by commas (e.g. 1,2,3): "
    )

    selected = set(choices.replace(" ", "").split(","))

    # Validate choices
    if not selected.issubset({"1", "2", "3", "4"}):
        print("Error: Please select only options 1, 2, 3, or 4.")
        return

    if len(selected) < 2:
        print("Error: Select at least two character types.")
        return

    # Create character groups
    groups = []

    if "1" in selected:
        groups.append(string.ascii_uppercase)

    if "2" in selected:
        groups.append(string.ascii_lowercase)

    if "3" in selected:
        groups.append(string.digits)

    if "4" in selected:
        groups.append(string.punctuation)

    # Generate a password containing every selected type
    password_chars = [random.choice(group) for group in groups]

    all_characters = "".join(groups)

    for _ in range(length - len(password_chars)):
        password_chars.append(random.choice(all_characters))

    random.shuffle(password_chars)

    password = "".join(password_chars)

    print("\n===== GENERATED PASSWORD =====")
    print("Your password is:", password)
    print("==============================")

# Allow generating another password
while True:
    generate_password()

    again = input("\nGenerate another password? (yes/no): ").lower()

    if again not in ("yes", "y"):
        print("Thank you for using Password Generator!")
        break